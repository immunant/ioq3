/*
==============
Sys_Dialog

Display a *nix dialog box
==============
*/
#[no_mangle]

pub unsafe extern "C" fn Sys_Dialog(
    mut type_0: dialogType_t,
    mut message: *const libc::c_char,
    mut title: *const libc::c_char,
) -> dialogResult_t {
    let mut session: *const libc::c_char =
        libc::getenv(b"DESKTOP_SESSION\x00" as *const u8 as *const libc::c_char);
    let mut tried: [qboolean; 4] = [qfalse, qfalse, qfalse, qfalse];
    let mut commands: [dialogCommandBuilder_t; 4] = [None, None, None, None];
    let mut preferredCommandType: dialogCommandType_t = NONE;
    let mut i: i32 = 0;
    commands[ZENITY as i32 as usize] = Some(
        Sys_ZenityCommand
            as unsafe extern "C" fn(
                _: dialogType_t,
                _: *const libc::c_char,
                _: *const libc::c_char,
            ) -> (),
    );
    commands[KDIALOG as i32 as usize] = Some(
        Sys_KdialogCommand
            as unsafe extern "C" fn(
                _: dialogType_t,
                _: *const libc::c_char,
                _: *const libc::c_char,
            ) -> (),
    );
    commands[XMESSAGE as i32 as usize] = Some(
        Sys_XmessageCommand
            as unsafe extern "C" fn(
                _: dialogType_t,
                _: *const libc::c_char,
                _: *const libc::c_char,
            ) -> (),
    );
    // This may not be the best way
    if Q_stricmp(session, b"gnome\x00" as *const u8 as *const libc::c_char) == 0 {
        preferredCommandType = ZENITY
    } else if Q_stricmp(session, b"kde\x00" as *const u8 as *const libc::c_char) == 0 {
        preferredCommandType = KDIALOG
    }
    i = NONE as i32 + 1 as i32;
    while i < NUM_DIALOG_PROGRAMS as i32 {
        if !(preferredCommandType as u32 != NONE as i32 as u32
            && preferredCommandType as u32 != i as u32)
        {
            if tried[i as usize] as u64 == 0 {
                let mut exitCode: i32 = 0;
                commands[i as usize].expect("non-null function pointer")(type_0, message, title);
                exitCode = Sys_Exec();
                if exitCode >= 0 as i32 {
                    match type_0 as u32 {
                        3 => {
                            return if exitCode != 0 {
                                DR_NO as i32
                            } else {
                                DR_YES as i32
                            } as dialogResult_t
                        }
                        4 => {
                            return if exitCode != 0 {
                                DR_CANCEL as i32
                            } else {
                                DR_OK as i32
                            } as dialogResult_t
                        }
                        _ => return DR_OK,
                    }
                }
                tried[i as usize] = qtrue;
                // The preference failed, so start again in order
                if preferredCommandType as u32 != NONE as i32 as u32 {
                    preferredCommandType = NONE;
                    i = NONE as i32 + 1 as i32
                }
            }
        }
        i += 1
    }
    Com_DPrintf(b"^3WARNING: failed to show a dialog\n\x00" as *const u8 as *const libc::c_char);
    return DR_OK;
}
