#[no_mangle]

pub unsafe extern "C" fn Sys_DefaultHomePath() -> *mut libc::c_char {
    let mut p: *mut libc::c_char = 0 as *mut libc::c_char;
    if *homePath.as_mut_ptr() == 0 && !com_homepath.is_null() {
        p = libc::getenv(b"HOME\x00" as *const u8 as *const libc::c_char);
        if !p.is_null() {
            Com_sprintf(
                homePath.as_mut_ptr(),
                ::std::mem::size_of::<[libc::c_char; 4096]>() as usize as i32,
                b"%s%c\x00" as *const u8 as *const libc::c_char,
                p,
                '/' as i32,
            );
            if *(*com_homepath).string.offset(0 as i32 as isize) != 0 {
                Q_strcat(
                    homePath.as_mut_ptr(),
                    ::std::mem::size_of::<[libc::c_char; 4096]>() as usize as i32,
                    (*com_homepath).string,
                );
            } else {
                Q_strcat(
                    homePath.as_mut_ptr(),
                    ::std::mem::size_of::<[libc::c_char; 4096]>() as usize as i32,
                    b".q3a\x00" as *const u8 as *const libc::c_char,
                );
            }
        }
    }
    return homePath.as_mut_ptr();
}
