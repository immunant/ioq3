/*
=================
Sys_DllExtension

Check if filename should be allowed to be loaded as a DLL.
=================
*/
#[no_mangle]

pub unsafe extern "C" fn Sys_DllExtension(mut name: *const libc::c_char) -> qboolean {
    let mut p: *const libc::c_char = 0 as *const libc::c_char;
    let mut c: libc::c_char = 0 as i32 as libc::c_char;
    if COM_CompareExtension(name, b".so\x00" as *const u8 as *const libc::c_char) as u64 != 0 {
        return qtrue;
    }
    // Check for format of filename.so.1.2.3
    p = libc::strstr(name, b".so.\x00" as *const u8 as *const libc::c_char);
    if !p.is_null() {
        p = p
            .offset(crate::stdlib::strlen(b".so\x00" as *const u8 as *const libc::c_char) as isize);
        // Check if .so is only followed for periods and numbers.
        while *p != 0 {
            c = *p;
            if *(*__ctype_b_loc()).offset(c as i32 as isize) as i32 & _ISdigit as i32 as u16 as i32
                == 0
                && c as i32 != '.' as i32
            {
                return qfalse;
            }
            p = p.offset(1)
        }
        // Don't allow filename to end in a period. file.so., file.so.0., etc
        if c as i32 != '.' as i32 {
            return qtrue;
        }
    }
    return qfalse;
}
