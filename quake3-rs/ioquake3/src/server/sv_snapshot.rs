/*
=============================================================================

Delta encode a client frame onto the network channel

A normal server packet will look like:

4	sequence number (high bit set if an oversize fragment)
<optional reliable commands>
1	svc_snapshot
4	last client reliable command
4	serverTime
1	lastframe for delta compression
1	snapFlags
1	areaBytes
<areabytes>
<playerstate>
<packetentities>

=============================================================================
*/
/*
=============
SV_EmitPacketEntities

Writes a delta update of an entityState_t list to the message.
=============
*/

unsafe extern "C" fn SV_EmitPacketEntities(
    mut from: *mut clientSnapshot_t,
    mut to: *mut clientSnapshot_t,
    mut msg: *mut msg_t,
) {
    let mut oldent: *mut entityState_t = 0 as *mut entityState_t;
    let mut newent: *mut entityState_t = 0 as *mut entityState_t;
    let mut oldindex: i32 = 0;
    let mut newindex: i32 = 0;
    let mut oldnum: i32 = 0;
    let mut newnum: i32 = 0;
    let mut from_num_entities: i32 = 0;
    // generate the delta update
    if from.is_null() {
        from_num_entities = 0 as i32
    } else {
        from_num_entities = (*from).num_entities
    }
    newent = 0 as *mut entityState_t;
    oldent = 0 as *mut entityState_t;
    newindex = 0 as i32;
    oldindex = 0 as i32;
    while newindex < (*to).num_entities || oldindex < from_num_entities {
        if newindex >= (*to).num_entities {
            newnum = 9999 as i32
        } else {
            newent = &mut *svs
                .snapshotEntities
                .offset((((*to).first_entity + newindex) % svs.numSnapshotEntities) as isize)
                as *mut entityState_t;
            newnum = (*newent).number
        }
        if oldindex >= from_num_entities {
            oldnum = 9999 as i32
        } else {
            oldent = &mut *svs
                .snapshotEntities
                .offset((((*from).first_entity + oldindex) % svs.numSnapshotEntities) as isize)
                as *mut entityState_t;
            oldnum = (*oldent).number
        }
        if newnum == oldnum {
            // delta update from old position
            // because the force parm is qfalse, this will not result
            // in any bytes being emitted if the entity has not changed at all
            MSG_WriteDeltaEntity(
                msg as *mut msg_t,
                oldent as *mut entityState_s,
                newent as *mut entityState_s,
                qfalse,
            );
            oldindex += 1;
            newindex += 1
        } else if newnum < oldnum {
            // this is a new entity, send it from the baseline
            MSG_WriteDeltaEntity(
                msg as *mut msg_t,
                &mut (*sv.svEntities.as_mut_ptr().offset(newnum as isize)).baseline as *mut _
                    as *mut entityState_s,
                newent as *mut entityState_s,
                qtrue,
            );
            newindex += 1
        } else {
            if !(newnum > oldnum) {
                continue;
            }
            // the old entity isn't present in the new message
            MSG_WriteDeltaEntity(
                msg as *mut msg_t,
                oldent as *mut entityState_s,
                0 as *mut entityState_s as *mut entityState_s,
                qtrue,
            );
            oldindex += 1
        }
    }
    MSG_WriteBits(
        msg as *mut msg_t,
        ((1 as i32) << 10 as i32) - 1 as i32,
        10 as i32,
    );
    // end of packetentities
}
/*
==================
SV_WriteSnapshotToClient
==================
*/

unsafe extern "C" fn SV_WriteSnapshotToClient(mut client: *mut client_t, mut msg: *mut msg_t) {
    let mut frame: *mut clientSnapshot_t = 0 as *mut clientSnapshot_t;
    let mut oldframe: *mut clientSnapshot_t = 0 as *mut clientSnapshot_t;
    let mut lastframe: i32 = 0;
    let mut i: i32 = 0;
    let mut snapFlags: i32 = 0;
    // this is the snapshot we are creating
    frame = &mut *(*client)
        .frames
        .as_mut_ptr()
        .offset(((*client).netchan.outgoingSequence & 32 as i32 - 1 as i32) as isize)
        as *mut clientSnapshot_t;
    // try to use a previous frame as the source for delta compressing the snapshot
    if (*client).deltaMessage <= 0 as i32 || (*client).state as u32 != CS_ACTIVE as i32 as u32 {
        // client is asking for a retransmit
        oldframe = 0 as *mut clientSnapshot_t;
        lastframe = 0 as i32
    } else if (*client).netchan.outgoingSequence - (*client).deltaMessage >= 32 as i32 - 3 as i32 {
        // client hasn't gotten a good message through in a long time
        Com_DPrintf(
            b"%s: Delta request from out of date packet.\n\x00" as *const u8 as *const libc::c_char,
            (*client).name.as_mut_ptr(),
        );
        oldframe = 0 as *mut clientSnapshot_t;
        lastframe = 0 as i32
    } else {
        // we have a valid snapshot to delta from
        oldframe = &mut *(*client)
            .frames
            .as_mut_ptr()
            .offset(((*client).deltaMessage & 32 as i32 - 1 as i32) as isize)
            as *mut clientSnapshot_t;
        lastframe = (*client).netchan.outgoingSequence - (*client).deltaMessage;
        // the snapshot's entities may still have rolled off the buffer, though
        if (*oldframe).first_entity <= svs.nextSnapshotEntities - svs.numSnapshotEntities {
            Com_DPrintf(
                b"%s: Delta request from out of date entities.\n\x00" as *const u8
                    as *const libc::c_char,
                (*client).name.as_mut_ptr(),
            );
            oldframe = 0 as *mut clientSnapshot_t;
            lastframe = 0 as i32
        }
    }
    MSG_WriteByte(msg as *mut msg_t, svc_snapshot as i32);
    // NOTE, MRE: now sent at the start of every message from server to client
    // let the client know which reliable clientCommands we have received
    //MSG_WriteLong( msg, client->lastClientCommand );
    // send over the current server time so the client can drift
    // its view of time to try to match
    if (*client).oldServerTime != 0 {
        // The server has not yet got an acknowledgement of the
        // new gamestate from this client, so continue to send it
        // a time as if the server has not restarted. Note from
        // the client's perspective this time is strictly speaking
        // incorrect, but since it'll be busy loading a map at
        // the time it doesn't really matter.
        MSG_WriteLong(msg as *mut msg_t, sv.time + (*client).oldServerTime);
    } else {
        MSG_WriteLong(msg as *mut msg_t, sv.time);
    }
    // what we are delta'ing from
    MSG_WriteByte(msg as *mut msg_t, lastframe);
    snapFlags = svs.snapFlagServerBit;
    if (*client).rateDelayed as u64 != 0 {
        snapFlags |= 1 as i32
    }
    if (*client).state as u32 != CS_ACTIVE as i32 as u32 {
        snapFlags |= 2 as i32
    }
    MSG_WriteByte(msg as *mut msg_t, snapFlags);
    // send over the areabits
    MSG_WriteByte(msg as *mut msg_t, (*frame).areabytes);
    MSG_WriteData(
        msg as *mut msg_t,
        (*frame).areabits.as_mut_ptr() as *const libc::c_void,
        (*frame).areabytes,
    );
    // delta encode the playerstate
    if !oldframe.is_null() {
        MSG_WriteDeltaPlayerstate(
            msg as *mut msg_t,
            &mut (*oldframe).ps as *mut _ as *mut playerState_s,
            &mut (*frame).ps as *mut _ as *mut playerState_s,
        );
    } else {
        MSG_WriteDeltaPlayerstate(
            msg as *mut msg_t,
            0 as *mut playerState_s as *mut playerState_s,
            &mut (*frame).ps as *mut _ as *mut playerState_s,
        );
    }
    // delta encode the entities
    SV_EmitPacketEntities(oldframe, frame, msg);
    // padding for rate debugging
    if (*sv_padPackets).integer != 0 {
        i = 0 as i32;
        while i < (*sv_padPackets).integer {
            MSG_WriteByte(msg as *mut msg_t, svc_nop as i32);
            i += 1
        }
    };
}
/*
==================
SV_UpdateServerCommandsToClient

(re)send all server commands the client hasn't acknowledged yet
==================
*/
#[no_mangle]

pub unsafe extern "C" fn SV_UpdateServerCommandsToClient(
    mut client: *mut client_t,
    mut msg: *mut msg_t,
) {
    let mut i: i32 = 0;
    // write any unacknowledged serverCommands
    i = (*client).reliableAcknowledge + 1 as i32;
    while i <= (*client).reliableSequence {
        MSG_WriteByte(msg as *mut msg_t, svc_serverCommand as i32);
        MSG_WriteLong(msg as *mut msg_t, i);
        MSG_WriteString(
            msg as *mut msg_t,
            (*client).reliableCommands[(i & 64 as i32 - 1 as i32) as usize].as_mut_ptr(),
        );
        i += 1
    }
    (*client).reliableSent = (*client).reliableSequence;
}
/*
=======================
SV_QsortEntityNumbers
=======================
*/

unsafe extern "C" fn SV_QsortEntityNumbers(
    mut a: *const libc::c_void,
    mut b: *const libc::c_void,
) -> i32 {
    let mut ea: *mut i32 = 0 as *mut i32;
    let mut eb: *mut i32 = 0 as *mut i32;
    ea = a as *mut i32;
    eb = b as *mut i32;
    if *ea == *eb {
        Com_Error(
            ERR_DROP as i32,
            b"SV_QsortEntityStates: duplicated entity\x00" as *const u8 as *const libc::c_char,
        );
    }
    if *ea < *eb {
        return -(1 as i32);
    }
    return 1 as i32;
}
/*
===============
SV_AddEntToSnapshot
===============
*/

unsafe extern "C" fn SV_AddEntToSnapshot(
    mut svEnt: *mut svEntity_t,
    mut gEnt: *mut sharedEntity_t,
    mut eNums: *mut snapshotEntityNumbers_t,
) {
    // if we have already added this entity to this snapshot, don't add again
    if (*svEnt).snapshotCounter == sv.snapshotCounter {
        return;
    }
    (*svEnt).snapshotCounter = sv.snapshotCounter;
    // if we are full, silently discard entities
    if (*eNums).numSnapshotEntities == 256 as i32 {
        return;
    }
    (*eNums).snapshotEntities[(*eNums).numSnapshotEntities as usize] = (*gEnt).s.number;
    (*eNums).numSnapshotEntities += 1;
}
