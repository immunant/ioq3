        crate::src::qcommon::cm_test::CM_WriteAreaBits((*frame).areabits.as_mut_ptr(), clientarea);
    clientpvs = crate::src::qcommon::cm_test::CM_ClusterPVS(clientcluster);
    let mut current_block_26: u64;
    e = 0 as i32;
