/* * @defgroup opus_custom Opus Custom
 * @{
 *  Opus Custom is an optional part of the Opus specification and
 * reference implementation which uses a distinct API from the regular
 * API and supports frame sizes that are not normally supported.\ Use
 * of Opus Custom is discouraged for all but very special applications
 * for which a frame size different from 2.5, 5, 10, or 20 ms is needed
 * (for either complexity or latency reasons) and where interoperability
 * is less important.
 *
 * In addition to the interoperability limitations the use of Opus custom
 * disables a substantial chunk of the codec and generally lowers the
 * quality available at a given bitrate. Normally when an application needs
 * a different frame size from the codec it should buffer to match the
 * sizes but this adds a small amount of delay which may be important
 * in some very low latency applications. Some transports (especially
 * constant rate RF transports) may also work best with frames of
 * particular durations.
 *
 * Libopus only supports custom modes if they are enabled at compile time.
 *
 * The Opus Custom API is similar to the regular API but the
 * @ref opus_encoder_create and @ref opus_decoder_create calls take
 * an additional mode parameter which is a structure produced by
 * a call to @ref opus_custom_mode_create. Both the encoder and decoder
 * must create a mode using the same sample rate (fs) and frame size
 * (frame size) so these parameters must either be signaled out of band
 * or fixed in a particular implementation.
 *
 * Similar to regular Opus the custom modes support on the fly frame size
 * switching, but the sizes available depend on the particular frame size in
 * use. For some initial frame sizes on a single on the fly size is available.
 */
/* * Contains the state of an encoder. One encoder state is needed
   for each stream. It is initialized once at the beginning of the
   stream. Do *not* re-initialize the state for every frame.
  @brief Encoder state
*/
/* * State of the decoder. One decoder state is needed for each stream.
   It is initialized once at the beginning of the stream. Do *not*
   re-initialize the state for every frame.
  @brief Decoder state
*/
/* * The mode contains all the information necessary to create an
   encoder. Both the encoder and decoder need to be initialized
   with exactly the same mode, otherwise the output will be
   corrupted.
  @brief Mode configuration
*/
/* * Creates a new mode struct. This will be passed to an encoder or
 * decoder. The mode MUST NOT BE DESTROYED until the encoders and
 * decoders that use it are destroyed as well.
 * @param [in] Fs <tt>int</tt>: Sampling rate (8000 to 96000 Hz)
 * @param [in] frame_size <tt>int</tt>: Number of samples (per channel) to encode in each
 *        packet (64 - 1024, prime factorization must contain zero or more 2s, 3s, or 5s and no other primes)
 * @param [out] error <tt>int*</tt>: Returned error code (if NULL, no error will be returned)
 * @return A newly created mode
 */
/* CUSTOM_MODES_ONLY */
/* CUSTOM_MODES */
#[no_mangle]

pub unsafe extern "C" fn opus_custom_mode_create(
    mut Fs: crate::opus_types_h::opus_int32,
    mut frame_size: i32,
    mut error: *mut i32,
) -> *mut crate::src::opus_1_2_1::celt::modes::OpusCustomMode {
    let mut i: i32 = 0;
    i = 0 as i32;
    while i < 1 as i32 {
        let mut j: i32 = 0;
        j = 0 as i32;
        while j < 4 as i32 {
            if Fs == (*static_mode_list[i as usize]).Fs
                && frame_size << j
                    == (*static_mode_list[i as usize]).shortMdctSize
                        * (*static_mode_list[i as usize]).nbShortMdcts
            {
                if !error.is_null() {
                    *error = 0 as i32
                }
                return static_mode_list[i as usize]
                    as *mut crate::src::opus_1_2_1::celt::modes::OpusCustomMode;
            }
            j += 1
        }
        i += 1
    }
    /* CUSTOM_MODES_ONLY */
    if !error.is_null() {
        *error = -(1 as i32)
    }
    return 0 as *mut crate::src::opus_1_2_1::celt::modes::OpusCustomMode;
    /* !CUSTOM_MODES */
}
