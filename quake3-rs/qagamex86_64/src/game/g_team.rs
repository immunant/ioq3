/*
================
Team_FragBonuses

Calculate the bonuses for flag defense, flag carrier defense, etc.
Note that bonuses are not cumulative.  You get one, they are in importance
order.
================
*/
#[no_mangle]

pub unsafe extern "C" fn Team_FragBonuses(
    mut targ: *mut gentity_t,
    mut _inflictor: *mut gentity_t,
    mut attacker: *mut gentity_t,
) {
    let mut i: i32 = 0;
    let mut ent: *mut gentity_t = 0 as *mut gentity_t;
    let mut flag_pw: i32 = 0;
    let mut enemy_flag_pw: i32 = 0;
    let mut otherteam: i32 = 0;
    let mut tokens: i32 = 0;
    let mut flag: *mut gentity_t = 0 as *mut gentity_t;
    let mut carrier: *mut gentity_t = 0 as *mut gentity_t;
    let mut c: *mut libc::c_char = 0 as *mut libc::c_char;
    let mut v1: vec3_t = [0.; 3];
    let mut v2: vec3_t = [0.; 3];
    let mut team: i32 = 0;
    // no bonus for fragging yourself or team mates
    if (*targ).client.is_null()
        || (*attacker).client.is_null()
        || targ == attacker
        || OnSameTeam(targ, attacker) as u32 != 0
    {
        return;
    } // whoever died isn't on a team
    team = (*(*targ).client).sess.sessionTeam as i32;
    otherteam = OtherTeam((*(*targ).client).sess.sessionTeam as i32);
    if otherteam < 0 as i32 {
        return;
    }
    // same team, if the flag at base, check to he has the enemy flag
    if team == TEAM_RED as i32 {
        flag_pw = PW_REDFLAG as i32;
        enemy_flag_pw = PW_BLUEFLAG as i32
    } else {
        flag_pw = PW_BLUEFLAG as i32;
        enemy_flag_pw = PW_REDFLAG as i32
    }
    // did the attacker frag the flag carrier?
    tokens = 0 as i32;
    if (*(*targ).client).ps.powerups[enemy_flag_pw as usize] != 0 {
        (*(*attacker).client).pers.teamState.lastfraggedcarrier = level.time as f32;
        AddScore(
            attacker as *mut gentity_s,
            (*targ).r.currentOrigin.as_mut_ptr(),
            2 as i32,
        );
        (*(*attacker).client).pers.teamState.fragcarrier += 1;
        PrintMsg(
            0 as *mut gentity_t,
            b"%s^7 fragged %s\'s flag carrier!\n\x00" as *const u8 as *const libc::c_char,
            (*(*attacker).client).pers.netname.as_mut_ptr(),
            TeamName(team),
        );
        // the target had the flag, clear the hurt carrier
        // field on the other team
        i = 0 as i32;
        while i < g_maxclients.integer {
            ent = g_entities.as_mut_ptr().offset(i as isize);
            if (*ent).inuse as u32 != 0
                && (*(*ent).client).sess.sessionTeam as u32 == otherteam as u32
            {
                (*(*ent).client).pers.teamState.lasthurtcarrier = 0 as i32 as f32
            }
            i += 1
        }
        return;
    }
    // did the attacker frag a head carrier? other->client->ps.generic1
    if tokens != 0 {
        (*(*attacker).client).pers.teamState.lastfraggedcarrier = level.time as f32;
        AddScore(
            attacker as *mut gentity_s,
            (*targ).r.currentOrigin.as_mut_ptr(),
            2 as i32 * tokens * tokens,
        );
        (*(*attacker).client).pers.teamState.fragcarrier += 1;
        PrintMsg(
            0 as *mut gentity_t,
            b"%s^7 fragged %s\'s skull carrier!\n\x00" as *const u8 as *const libc::c_char,
            (*(*attacker).client).pers.netname.as_mut_ptr(),
            TeamName(team),
        );
        // the target had the flag, clear the hurt carrier
        // field on the other team
        i = 0 as i32;
        while i < g_maxclients.integer {
            ent = g_entities.as_mut_ptr().offset(i as isize);
            if (*ent).inuse as u32 != 0
                && (*(*ent).client).sess.sessionTeam as u32 == otherteam as u32
            {
                (*(*ent).client).pers.teamState.lasthurtcarrier = 0 as i32 as f32
            }
            i += 1
        }
        return;
    }
    if (*(*targ).client).pers.teamState.lasthurtcarrier != 0.
        && level.time as f32 - (*(*targ).client).pers.teamState.lasthurtcarrier < 8000 as i32 as f32
        && (*(*attacker).client).ps.powerups[flag_pw as usize] == 0
    {
        // attacker is on the same team as the flag carrier and
        // fragged a guy who hurt our flag carrier
        AddScore(
            attacker as *mut gentity_s,
            (*targ).r.currentOrigin.as_mut_ptr(),
            2 as i32,
        );
        (*(*attacker).client).pers.teamState.carrierdefense += 1;
        (*(*targ).client).pers.teamState.lasthurtcarrier = 0 as i32 as f32;
        (*(*attacker).client).ps.persistant[PERS_DEFEND_COUNT as i32 as usize] += 1;
        // add the sprite over the player's head
        (*(*attacker).client).ps.eFlags &= !(0x8000 as i32
            | 0x8 as i32
            | 0x40 as i32
            | 0x20000 as i32
            | 0x10000 as i32
            | 0x800 as i32);
        (*(*attacker).client).ps.eFlags |= 0x10000 as i32;
        (*(*attacker).client).rewardTime = level.time + 2000 as i32;
        return;
    }
    // flag and flag carrier area defense bonuses
    // we have to find the flag and carrier entities
    // find the flag
    match (*(*attacker).client).sess.sessionTeam as u32 {
        1 => c = b"team_CTF_redflag\x00" as *const u8 as *const libc::c_char as *mut libc::c_char,
        2 => c = b"team_CTF_blueflag\x00" as *const u8 as *const libc::c_char as *mut libc::c_char,
        _ => return,
    }
    // find attacker's team's flag carrier
    i = 0 as i32; // can't find attacker's flag
    while i < g_maxclients.integer {
        carrier = g_entities.as_mut_ptr().offset(i as isize);
        if (*carrier).inuse as u32 != 0 && (*(*carrier).client).ps.powerups[flag_pw as usize] != 0 {
            break;
        }
        carrier = 0 as *mut gentity_t;
        i += 1
    }
    flag = 0 as *mut gentity_t;
    loop {
        flag = G_Find(
            flag as *mut gentity_s,
            &mut (*(0 as *mut gentity_t)).classname as *mut *mut libc::c_char as size_t as i32,
            c,
        ) as *mut gentity_s;
        if flag.is_null() {
            break;
        }
        if (*flag).flags & 0x1000 as i32 == 0 {
            break;
        }
    }
    if flag.is_null() {
        return;
    }
    // ok we have the attackers flag and a pointer to the carrier
    // check to see if we are defending the base's flag
    v1[0 as i32 as usize] =
        (*targ).r.currentOrigin[0 as i32 as usize] - (*flag).r.currentOrigin[0 as i32 as usize];
    v1[1 as i32 as usize] =
        (*targ).r.currentOrigin[1 as i32 as usize] - (*flag).r.currentOrigin[1 as i32 as usize];
    v1[2 as i32 as usize] =
        (*targ).r.currentOrigin[2 as i32 as usize] - (*flag).r.currentOrigin[2 as i32 as usize];
    v2[0 as i32 as usize] =
        (*attacker).r.currentOrigin[0 as i32 as usize] - (*flag).r.currentOrigin[0 as i32 as usize];
    v2[1 as i32 as usize] =
        (*attacker).r.currentOrigin[1 as i32 as usize] - (*flag).r.currentOrigin[1 as i32 as usize];
    v2[2 as i32 as usize] =
        (*attacker).r.currentOrigin[2 as i32 as usize] - (*flag).r.currentOrigin[2 as i32 as usize];
    if (VectorLength(v1.as_mut_ptr() as *const vec_t) < 1000 as i32 as f32
        && trap_InPVS(
            (*flag).r.currentOrigin.as_mut_ptr() as *const vec_t,
            (*targ).r.currentOrigin.as_mut_ptr() as *const vec_t,
        ) as u32
            != 0
        || VectorLength(v2.as_mut_ptr() as *const vec_t) < 1000 as i32 as f32
            && trap_InPVS(
                (*flag).r.currentOrigin.as_mut_ptr() as *const vec_t,
                (*attacker).r.currentOrigin.as_mut_ptr() as *const vec_t,
            ) as u32
                != 0)
        && (*(*attacker).client).sess.sessionTeam as u32
            != (*(*targ).client).sess.sessionTeam as u32
    {
        // we defended the base flag
        AddScore(
            attacker as *mut gentity_s,
            (*targ).r.currentOrigin.as_mut_ptr(),
            1 as i32,
        );
        (*(*attacker).client).pers.teamState.basedefense += 1;
        (*(*attacker).client).ps.persistant[PERS_DEFEND_COUNT as i32 as usize] += 1;
        // add the sprite over the player's head
        (*(*attacker).client).ps.eFlags &= !(0x8000 as i32
            | 0x8 as i32
            | 0x40 as i32
            | 0x20000 as i32
            | 0x10000 as i32
            | 0x800 as i32);
        (*(*attacker).client).ps.eFlags |= 0x10000 as i32;
        (*(*attacker).client).rewardTime = level.time + 2000 as i32;
        return;
    }
    if !carrier.is_null() && carrier != attacker {
        v1[0 as i32 as usize] = (*targ).r.currentOrigin[0 as i32 as usize]
            - (*carrier).r.currentOrigin[0 as i32 as usize];
        v1[1 as i32 as usize] = (*targ).r.currentOrigin[1 as i32 as usize]
            - (*carrier).r.currentOrigin[1 as i32 as usize];
        v1[2 as i32 as usize] = (*targ).r.currentOrigin[2 as i32 as usize]
            - (*carrier).r.currentOrigin[2 as i32 as usize];
        v2[0 as i32 as usize] = (*attacker).r.currentOrigin[0 as i32 as usize]
            - (*carrier).r.currentOrigin[0 as i32 as usize];
        v2[1 as i32 as usize] = (*attacker).r.currentOrigin[1 as i32 as usize]
            - (*carrier).r.currentOrigin[1 as i32 as usize];
        v2[2 as i32 as usize] = (*attacker).r.currentOrigin[2 as i32 as usize]
            - (*carrier).r.currentOrigin[2 as i32 as usize];
        if (VectorLength(v1.as_mut_ptr() as *const vec_t) < 1000 as i32 as f32
            && trap_InPVS(
                (*carrier).r.currentOrigin.as_mut_ptr() as *const vec_t,
                (*targ).r.currentOrigin.as_mut_ptr() as *const vec_t,
            ) as u32
                != 0
            || VectorLength(v2.as_mut_ptr() as *const vec_t) < 1000 as i32 as f32
                && trap_InPVS(
                    (*carrier).r.currentOrigin.as_mut_ptr() as *const vec_t,
                    (*attacker).r.currentOrigin.as_mut_ptr() as *const vec_t,
                ) as u32
                    != 0)
            && (*(*attacker).client).sess.sessionTeam as u32
                != (*(*targ).client).sess.sessionTeam as u32
        {
            AddScore(
                attacker as *mut gentity_s,
                (*targ).r.currentOrigin.as_mut_ptr(),
                1 as i32,
            );
            (*(*attacker).client).pers.teamState.carrierdefense += 1;
            (*(*attacker).client).ps.persistant[PERS_DEFEND_COUNT as i32 as usize] += 1;
            // add the sprite over the player's head
            (*(*attacker).client).ps.eFlags &= !(0x8000 as i32
                | 0x8 as i32
                | 0x40 as i32
                | 0x20000 as i32
                | 0x10000 as i32
                | 0x800 as i32);
            (*(*attacker).client).ps.eFlags |= 0x10000 as i32;
            (*(*attacker).client).rewardTime = level.time + 2000 as i32;
            return;
        }
    };
}
