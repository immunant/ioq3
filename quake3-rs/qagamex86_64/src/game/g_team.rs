unsafe extern "C" fn SortClients(mut a: *const libc::c_void, mut b: *const libc::c_void) -> i32 {
    return *(a as *mut i32) - *(b as *mut i32);
}
/*
==================
TeamplayLocationsMessage

Format:
    clientNum location health armor weapon powerups

==================
*/
#[no_mangle]

pub unsafe extern "C" fn TeamplayInfoMessage(mut ent: *mut gentity_t) {
    let mut entry: [libc::c_char; 1024] = [0; 1024];
    let mut string: [libc::c_char; 8192] = [0; 8192];
    let mut stringlength: i32 = 0;
    let mut i: i32 = 0;
    let mut j: i32 = 0;
    let mut player: *mut gentity_t = 0 as *mut gentity_t;
    let mut cnt: i32 = 0;
    let mut h: i32 = 0;
    let mut a: i32 = 0;
    let mut clients: [i32; 32] = [0; 32];
    let mut team: i32 = 0;
    if (*(*ent).client).pers.teamInfo as u64 == 0 {
        return;
    }
    // send team info to spectator for team of followed client
    if (*(*ent).client).sess.sessionTeam as u32 == TEAM_SPECTATOR as i32 as u32 {
        if (*(*ent).client).sess.spectatorState as u32 != SPECTATOR_FOLLOW as i32 as u32
            || (*(*ent).client).sess.spectatorClient < 0 as i32
        {
            return;
        }
        team = (*g_entities[(*(*ent).client).sess.spectatorClient as usize].client)
            .sess
            .sessionTeam as i32
    } else {
        team = (*(*ent).client).sess.sessionTeam as i32
    }
    if team != TEAM_RED as i32 && team != TEAM_BLUE as i32 {
        return;
    }
    // figure out what client should be on the display
    // we are limited to 8, but we want to use the top eight players
    // but in client order (so they don't keep changing position on the overlay)
    i = 0 as i32;
    cnt = 0 as i32;
    while i < g_maxclients.integer && cnt < 32 as i32 {
        player = g_entities
            .as_mut_ptr()
            .offset(level.sortedClients[i as usize] as isize);
        if (*player).inuse as u32 != 0 && (*(*player).client).sess.sessionTeam as u32 == team as u32
        {
            let fresh1 = cnt;
            cnt = cnt + 1;
            clients[fresh1 as usize] = level.sortedClients[i as usize]
        }
        i += 1
    }
    // We have the top eight players, sort them by clientNum
    qsort(
        clients.as_mut_ptr() as *mut libc::c_void,
        cnt as size_t,
        ::std::mem::size_of::<i32>() as usize,
        Some(
            SortClients
                as unsafe extern "C" fn(_: *const libc::c_void, _: *const libc::c_void) -> i32,
        ),
    );
    // send the latest information on all clients
    string[0 as i32 as usize] = 0 as i32 as libc::c_char;
    stringlength = 0 as i32;
    i = 0 as i32;
    cnt = 0 as i32;
    while i < g_maxclients.integer && cnt < 32 as i32 {
        player = g_entities.as_mut_ptr().offset(i as isize);
        if (*player).inuse as u32 != 0 && (*(*player).client).sess.sessionTeam as u32 == team as u32
        {
            h = (*(*player).client).ps.stats[STAT_HEALTH as i32 as usize];
            a = (*(*player).client).ps.stats[STAT_ARMOR as i32 as usize];
            if h < 0 as i32 {
                h = 0 as i32
            }
            if a < 0 as i32 {
                a = 0 as i32
            }
            Com_sprintf(
                entry.as_mut_ptr(),
                ::std::mem::size_of::<[libc::c_char; 1024]>() as usize as i32,
                b" %i %i %i %i %i %i\x00" as *const u8 as *const libc::c_char,
                i,
                (*(*player).client).pers.teamState.location,
                h,
                a,
                (*(*player).client).ps.weapon,
                (*player).s.powerups,
            );
            j = crate::stdlib::strlen(entry.as_mut_ptr()) as i32;
            if (stringlength + j) as usize
                >= ::std::mem::size_of::<[libc::c_char; 8192]>() as usize
            {
                break;
            }
            libc::strcpy(
                string.as_mut_ptr().offset(stringlength as isize),
                entry.as_mut_ptr(),
            );
            stringlength += j;
            cnt += 1
        }
        i += 1
    }
    trap_SendServerCommand(
        ent.offset_from(g_entities.as_mut_ptr()) as isize as i32,
        va(
            b"tinfo %i %s\x00" as *const u8 as *const libc::c_char as *mut libc::c_char,
            cnt,
            string.as_mut_ptr(),
        ),
    );
}
