#[no_mangle]

pub unsafe extern "C" fn SelectRandomTeamSpawnPoint(
    mut teamstate: i32,
    mut team: team_t,
) -> *mut gentity_t {
    let mut spot: *mut gentity_t = 0 as *mut gentity_t;
    let mut count: i32 = 0;
    let mut selection: i32 = 0;
    let mut spots: [*mut gentity_t; 32] = [0 as *mut gentity_t; 32];
    let mut classname: *mut libc::c_char = 0 as *mut libc::c_char;
    if teamstate == TEAM_BEGIN as i32 {
        if team as u32 == TEAM_RED as i32 as u32 {
            classname =
                b"team_CTF_redplayer\x00" as *const u8 as *const libc::c_char as *mut libc::c_char
        } else if team as u32 == TEAM_BLUE as i32 as u32 {
            classname =
                b"team_CTF_blueplayer\x00" as *const u8 as *const libc::c_char as *mut libc::c_char
        } else {
            return 0 as *mut gentity_t;
        }
    } else if team as u32 == TEAM_RED as i32 as u32 {
        classname =
            b"team_CTF_redspawn\x00" as *const u8 as *const libc::c_char as *mut libc::c_char
    } else if team as u32 == TEAM_BLUE as i32 as u32 {
        classname =
            b"team_CTF_bluespawn\x00" as *const u8 as *const libc::c_char as *mut libc::c_char
    } else {
        return 0 as *mut gentity_t;
    }
    count = 0 as i32;
    spot = 0 as *mut gentity_t;
    loop {
        spot = G_Find(
            spot as *mut gentity_s,
            &mut (*(0 as *mut gentity_t)).classname as *mut *mut libc::c_char as size_t as i32,
            classname,
        ) as *mut gentity_s;
        if spot.is_null() {
            break;
        }
        if SpotWouldTelefrag(spot as *mut gentity_s) as u64 != 0 {
            continue;
        }
        spots[count as usize] = spot;
        count += 1;
        if count == 32 as i32 {
            break;
        }
    }
    if count == 0 {
        // no spots that won't telefrag
        return G_Find(
            0 as *mut gentity_t as *mut gentity_s,
            &mut (*(0 as *mut gentity_t)).classname as *mut *mut libc::c_char as size_t as i32,
            classname,
        ) as *mut gentity_s;
    }
    selection = rand() % count;
    return spots[selection as usize];
}
/*
===========
SelectCTFSpawnPoint

============
*/
#[no_mangle]

pub unsafe extern "C" fn SelectCTFSpawnPoint(
    mut team: team_t,
    mut teamstate: i32,
    mut origin: *mut vec_t,
    mut angles: *mut vec_t,
    mut isbot: qboolean,
) -> *mut gentity_t {
    let mut spot: *mut gentity_t = 0 as *mut gentity_t;
    spot = SelectRandomTeamSpawnPoint(teamstate, team);
    if spot.is_null() {
        return SelectSpawnPoint(vec3_origin.as_mut_ptr(), origin, angles, isbot) as *mut gentity_s;
    }
    *origin.offset(0 as i32 as isize) = (*spot).s.origin[0 as i32 as usize];
    *origin.offset(1 as i32 as isize) = (*spot).s.origin[1 as i32 as usize];
    *origin.offset(2 as i32 as isize) = (*spot).s.origin[2 as i32 as usize];
    let ref mut fresh0 = *origin.offset(2 as i32 as isize);
    *fresh0 += 9 as i32 as f32;
    *angles.offset(0 as i32 as isize) = (*spot).s.angles[0 as i32 as usize];
    *angles.offset(1 as i32 as isize) = (*spot).s.angles[1 as i32 as usize];
    *angles.offset(2 as i32 as isize) = (*spot).s.angles[2 as i32 as usize];
    return spot;
}
